"""Render an Azure DevOps pipeline that extends the PipeSmith org templates."""
from __future__ import annotations

from . import __version__
from .detect import STATIC_TARGETS, Detection


def _q(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def render(det: Detection, *, app_name: str, service_connection: str,
           templates_repo: str = "Platform/pipeline-templates",
           templates_ref: str = "refs/tags/v1.0.0",
           environment: str = "production",
           fail_on: str = "high",
           branch: str = "main",
           variable_group: str = "pipesmith") -> str:
    if fail_on not in ("high", "critical"):
        raise ValueError("fail_on must be 'high' or 'critical'")
    evidence = "\n".join(f"#   - {e}" for e in det.evidence)
    lines = [
        f"# Generated by PipeSmith {__version__}. Re-run `pipesmith generate` instead of editing by hand.",
        f"# Detected: {det.stack} / {det.target}",
        evidence,
        "# Security gates, SBOM and signing come from the org template and cannot be removed here.",
        "",
        "trigger:",
        "  branches:",
        "    include:",
        f"      - {branch}",
        "",
        "resources:",
        "  repositories:",
        "    - repository: templates",
        "      type: git",
        f"      name: {templates_repo}",
        f"      ref: {templates_ref}",
        "",
        "extends:",
        "  template: pipeline.yml@templates",
        "  parameters:",
        f"    stack: {det.stack}",
        f"    target: {det.target}",
        f"    workingDirectory: {_q(det.working_directory)}",
        f"    runtimeVersion: {_q(det.runtime_version)}",
    ]
    if det.target in STATIC_TARGETS:
        lines.append(f"    buildOutput: {_q(det.build_output)}")
    lines += [
        f"    appName: {_q(app_name)}",
        f"    azureSubscription: {_q(service_connection)}",
        f"    environment: {_q(environment)}",
        f"    failOnSeverity: {fail_on}",
        f"    variableGroup: {_q(variable_group)}",
        f"    deployBranch: {_q('refs/heads/' + branch)}",
        "    # Add team-specific build steps here; they run after the standard build, before packaging.",
        "    extraBuildSteps: []",
        "",
    ]
    return "\n".join(lines)
